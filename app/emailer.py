import os
import smtplib
import ssl
from datetime import datetime
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from html import escape

from dotenv import load_dotenv


load_dotenv()


SUMMARY_CHARS = 350


def _short(text: str, limit: int = SUMMARY_CHARS) -> str:
    """Trim text to a word boundary."""

    text = " ".join(text.split())

    if len(text) <= limit:
        return text

    return text[:limit].rsplit(" ", 1)[0] + "..."


def build_subject(count: int) -> str:
    today = datetime.now().strftime("%d %b %Y")

    return f"SmartDigest: your top {count} for {today}"


def build_html(name: str, items: list[dict]) -> str:
    """Render the digest as an HTML email using inline styles."""

    cards = []

    for position, item in enumerate(items, start=1):
        title = escape(item["title"])
        url = escape(item["url"], quote=True)
        source = escape(item["source"])
        reason = escape(item["reason"])
        summary = escape(_short(item["summary"]))
        kind = "Video" if item["item_type"] == "video" else "Article"

        cards.append(
            f"""
<div style="padding:16px 0;border-bottom:1px solid #e5e7eb;">
  <div style="font-size:12px;color:#6b7280;">
    #{position} &middot; {kind} &middot; {source}
    &middot; <b style="color:#2563eb;">{item["score"]}/10</b>
  </div>
  <div style="font-size:17px;font-weight:600;margin:4px 0 6px;">
    <a href="{url}" style="color:#111827;text-decoration:none;">{title}</a>
  </div>
  <div style="font-size:14px;color:#374151;line-height:1.5;">{summary}</div>
  <div style="font-size:13px;color:#6b7280;margin-top:6px;">
    <i>Why this: {reason}</i>
  </div>
</div>"""
        )

    body = "\n".join(cards)

    return f"""<!DOCTYPE html>
<html>
<body style="margin:0;padding:0;background:#f9fafb;
font-family:-apple-system,Segoe UI,Roboto,Arial,sans-serif;">
  <div style="max-width:640px;margin:0 auto;padding:24px;background:#ffffff;">
    <h2 style="margin:0 0 4px;">SmartDigest</h2>
    <div style="color:#6b7280;font-size:14px;">
      Hi {escape(name)}, here are today's top picks for you.
    </div>
    {body}
    <div style="font-size:12px;color:#9ca3af;margin-top:20px;">
      Summaries and scores are generated by AI and may contain mistakes.
    </div>
  </div>
</body>
</html>"""


def build_text(name: str, items: list[dict]) -> str:
    """Plain-text fallback for email clients that block HTML."""

    lines = [f"Hi {name}, here are today's top picks for you.", ""]

    for position, item in enumerate(items, start=1):
        lines.append(f"{position}. [{item['score']}/10] {item['title']}")
        lines.append(f"   {item['source']} | {item['url']}")
        lines.append(f"   {_short(item['summary'])}")
        lines.append(f"   Why this: {item['reason']}")
        lines.append("")

    return "\n".join(lines)


def send_email(
    to_email: str,
    subject: str,
    html: str,
    text: str,
) -> None:
    """Send a multipart (text + HTML) email over SMTP."""

    host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    port = int(os.getenv("SMTP_PORT", "465"))
    user = os.getenv("SMTP_USER")

    # Gmail shows app passwords with spaces; they are not part of the password.
    password = (os.getenv("SMTP_PASSWORD") or "").replace(" ", "")

    sender = os.getenv("EMAIL_FROM") or user

    if not user or not password:
        raise ValueError(
            "SMTP_USER and SMTP_PASSWORD are not set. "
            "Add them to the .env file."
        )

    message = MIMEMultipart("alternative")
    message["Subject"] = subject
    message["From"] = f"SmartDigest <{sender}>"
    message["To"] = to_email

    message.attach(MIMEText(text, "plain", "utf-8"))
    message.attach(MIMEText(html, "html", "utf-8"))

    context = ssl.create_default_context()

    if port == 465:
        with smtplib.SMTP_SSL(host, port, context=context, timeout=30) as server:
            server.login(user, password)
            server.sendmail(sender, [to_email], message.as_string())

    else:
        with smtplib.SMTP(host, port, timeout=30) as server:
            server.starttls(context=context)
            server.login(user, password)
            server.sendmail(sender, [to_email], message.as_string())
